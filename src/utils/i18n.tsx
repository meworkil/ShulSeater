interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, defaultText?: string) => string;
  dir: 'ltr' | 'rtl';
  currentLangMeta: LanguageOption;
}

const I18nContext = createContext<I18nContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key) => key,
  dir: 'ltr',
  currentLangMeta: LANGUAGES[0]
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('koveamakom_language');
    return (saved as Language) || 'en';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('koveamakom_language', lang);
  };

  const currentLangMeta = LANGUAGES.find(l => l.code === language) || LANGUAGES[0];
  const dir = currentLangMeta.dir;

  useEffect(() => {
    document.documentElement.dir = dir;
    document.documentElement.lang = language;
  }, [dir, language]);

  const t = (key: string, defaultText?: string): string => {
    const dictionary = TRANSLATIONS[language] || TRANSLATIONS.en;
    if (dictionary && dictionary[key]) {
      return dictionary[key];
    }
    const fallback = TRANSLATIONS.en[key];
    if (fallback) return fallback;
    return defaultText || key;
  };

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, dir, currentLangMeta }}>
      <div dir={dir} className={dir === 'rtl' ? 'font-sans rtl' : 'font-sans'}>
        {children}
      </div>
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
